module TestAqua

using Test

import Aqua
import LinearDecisionRules

function runtests()
    for name in names(@__MODULE__; all = true)
        if startswith("$name", "test_")
            @testset "$name" begin
                getfield(@__MODULE__, name)()
            end
        end
    end
    return
end

function test_aqua()
    Aqua.test_all(LinearDecisionRules)
    return
end

end # module TestAqua

TestAqua.runtests()
